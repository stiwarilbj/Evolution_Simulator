import { expect, test } from '@playwright/test'

async function openWalkthrough(page, live = false) {
  await page.addInitScript(() => localStorage.setItem('evolution.tour', '1'))
  await page.goto('./')
  if (live) {
    await page.getByRole('button', { name:'Simulation Settings' }).click()
    await page.getByLabel('Run name').fill('Guided replay check')
    await page.getByRole('button', { name:/^Watch live/ }).click()
    await page.getByRole('button', { name:'Evolve!' }).click()
    await expect(page.getByRole('button', { name:'Run options' })).toContainText('Day 1 / 50 · Ready')
  }
  await page.getByRole('link', { name:'About', exact:true }).click()
}

test('the illustrated walkthrough opens a real family replay @pages', async ({ page }) => {
  await page.emulateMedia({ reducedMotion:'reduce' })
  await openWalkthrough(page, true)
  const panel = page.locator('.chapter-panel')
  await expect(panel.getByRole('heading', { name:'Natural selection' })).toBeVisible()
  await expect.poll(() => panel.getByRole('img', { name:/Four finch profiles/ }).evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
  await panel.getByRole('button', { name:'Primer', exact:true }).click()
  await expect(panel.getByRole('img')).toHaveCount(3)
  await expect.poll(() => panel.getByRole('img').evaluateAll(images => images.every(img => img.naturalWidth > 0))).toBe(true)
  await panel.getByRole('button', { name:'The host', exact:true }).click()
  await expect(panel.getByRole('img', { name:/science host/ })).toBeVisible()

  await page.getByRole('button', { name:'A newborn’s sight', exact:true }).click()
  const activeRun = page.getByRole('button', { name:'Run options' })
  const runAddress = new URL(page.url()).hash.split('/about')[0]
  await page.getByRole('button', { name:'Try it in World' }).click()
  await expect(page).toHaveURL(/example=offspring&lesson=offspring$/)
  const guide = page.getByRole('main', { name:'From parent to offspring' })
  await expect(guide).toBeVisible()
  const focus = guide.getByRole('button', { name:'Sense focus' })
  const summary = guide.locator('.guided-summary')
  const parent = guide.getByRole('button', { name:'Parent returns to refuge' })
  await expect(parent).toHaveAttribute('aria-pressed', 'true')
  await expect(summary).toContainText(/Sight 16\b/)
  await expect(focus).toHaveAttribute('aria-pressed', 'false')

  await guide.getByRole('button', { name:'Play example', exact:true }).click()
  const birth = guide.getByRole('button', { name:'A newborn at dusk' })
  await expect(birth).toHaveAttribute('aria-pressed', 'true')
  await guide.getByRole('button', { name:'Pause example' }).click()
  const readSubject = async () => (await summary.innerText()).match(/Blob #(\d+) · Sight ([\d.]+)/)
  const [, childId, childSight] = await readSubject()
  expect(Number(childSight)).toBeGreaterThan(0)
  expect(Number(childSight)).toBeLessThan(5)

  const next = guide.getByRole('button', { name:'The offspring searches on Day 2' })
  await next.click()
  await expect(next).toHaveAttribute('aria-pressed', 'true')
  await expect(focus).toHaveAttribute('aria-pressed', 'true')
  await expect(summary).toContainText('Blob #' + childId + ' · Sight ' + childSight)
  await expect(guide.locator('.close-vision path')).toHaveAttribute('d', /ZM/)
  await focus.click()
  await expect(guide.locator('.close-vision')).toHaveCount(0)
  await focus.click()
  await expect(guide.locator('.close-vision')).toBeVisible()

  await guide.getByRole('button', { name:'Back to walkthrough' }).click()
  await expect(panel.getByRole('heading', { name:'A newborn’s sight' })).toBeVisible()
  await page.goBack()
  await expect(guide).toBeVisible()
  await expect(parent).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(parent).toHaveAttribute('aria-pressed', 'true')
  expect(new URL(page.url()).hash.split('/viewer')[0]).toBe(runAddress)
  await page.getByRole('link', { name:'World', exact:true }).click()
  await expect(page.getByRole('button', { name:'Play', exact:true })).toBeEnabled()
  await expect(activeRun).toHaveText('Day 1 / 50 · Ready')
})

test('the stride race and energy lesson explain what bigger blobs spend', async ({ page }) => {
  await openWalkthrough(page)
  await page.getByRole('button', { name:'Size and stride', exact:true }).click()
  const panel = page.locator('.chapter-panel')
  await panel.getByText('See the original Rust rule').click()
  await expect(panel.locator('code')).toContainText('self.speed.0 * self.size.0 / 10.')
  await expect(panel.locator('.stride-flag')).toHaveCount(2)
  await page.clock.install()
  await panel.getByRole('button', { name:'Play race' }).click()
  await page.clock.runFor(2100)
  await expect(panel.locator('.stride-lane output')).toHaveText(['60 / 60 units', '50 / 60 units'])
  await panel.getByRole('button', { name:'Pause race' }).click()
  await page.clock.runFor(420)
  await expect(panel.getByText('Step 5 · 0.5 s')).toBeVisible()
  await panel.getByRole('button', { name:'Play race' }).click()
  await page.clock.runFor(420)
  await expect(panel.locator('.stride-lane output')).toHaveText(['60 / 60 units', '60 / 60 units'])
  await expect(panel.getByRole('button', { name:'Race again' })).toBeEnabled()
  await panel.getByRole('button', { name:'Reset race' }).click()
  await expect(panel.locator('.stride-foot')).toHaveCount(0)
  await page.getByRole('button', { name:'The cost of moving', exact:true }).click()
  await expect(panel.getByRole('heading', { name:'What helps find food' })).toBeVisible()
  await expect(panel.getByRole('heading', { name:'Energy spent per move' })).toBeVisible()
  await expect(panel).toContainText('10.002')
  await expect(panel).toContainText('24.885')
  await page.getByRole('button', { name:'Try it in World' }).click()
  const guide = page.getByRole('main', { name:'A fixed energy budget' })
  await expect(guide.getByRole('heading', { name:'Energy cost' })).toBeVisible()
  await expect(guide.locator('.guided-summary')).toContainText(/Energy \d+/)
  await expect(guide.getByRole('button', { name:'Pause example' })).toBeVisible()
})

test('a scarcity replay ends on its Day 4 extinction tile', async ({ page }) => {
  await page.emulateMedia({ reducedMotion:'reduce' })
  await openWalkthrough(page)
  await page.getByRole('button', { name:'Extinction', exact:true }).click()
  await page.getByRole('button', { name:'Try it in World' }).click()
  const guide = page.getByRole('main', { name:'The last generation' })
  const progress = guide.getByRole('slider', { name:'Example progress' })
  await expect(progress).toBeEnabled()
  await progress.press('End')
  const tile = guide.getByRole('button', { name:/Extinction on Day 4/ })
  await expect(tile).toBeVisible()
  await tile.click()
  await expect(tile).toBeHidden()
  await expect(progress).toHaveValue('0')
})
